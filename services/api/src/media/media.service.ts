import { BadRequestException, Injectable } from '@nestjs/common';
import {
  createImageProvider,
  createSpeechProvider,
  type GeneratedAsset,
} from '@agentos/llm';
import { assertAllowedUrl } from '@agentos/tools';
import { SecretsService } from '../secrets/secrets.service';

/** Reject a custom provider baseUrl that points at a private/loopback/link-local/metadata host
 * (SSRF + key-exfiltration guard) before we POST the decrypted key to it. */
async function assertSafeBaseUrl(baseUrl: string | undefined): Promise<void> {
  if (!baseUrl) return;
  try {
    await assertAllowedUrl(baseUrl);
  } catch (err) {
    throw new BadRequestException(
      `Provider baseUrl is not allowed: ${err instanceof Error ? err.message : String(err)}`,
    );
  }
}

/**
 * Media generation (images + speech) for the agent's generate_image / generate_speech tools. Loads
 * the workspace's encrypted provider config (server-side only), builds the provider, and returns the
 * generated bytes. No config => a clear error (never a silent placeholder).
 */
@Injectable()
export class MediaService {
  constructor(private readonly secrets: SecretsService) {}

  /** Cheap (non-decrypting) checks so a task only advertises the tools whose provider is configured. */
  async hasImageProvider(workspaceId: string): Promise<boolean> {
    return (await this.secrets.getImageInfo(workspaceId)).configured;
  }
  async hasSpeechProvider(workspaceId: string): Promise<boolean> {
    return (await this.secrets.getSpeechInfo(workspaceId)).configured;
  }

  async generateImage(workspaceId: string, prompt: string, opts?: { size?: string }): Promise<GeneratedAsset> {
    const config = await this.secrets.getImageConfig(workspaceId);
    if (!config) {
      throw new BadRequestException('No image provider configured. Add one in Settings → Media.');
    }
    await assertSafeBaseUrl(config.baseUrl);
    return createImageProvider(config).generate(prompt, opts);
  }

  async generateSpeech(workspaceId: string, text: string): Promise<GeneratedAsset> {
    const config = await this.secrets.getSpeechConfig(workspaceId);
    if (!config) {
      throw new BadRequestException('No speech provider configured. Add one in Settings → Media.');
    }
    await assertSafeBaseUrl(config.baseUrl);
    return createSpeechProvider(config).synthesize(text);
  }
}
